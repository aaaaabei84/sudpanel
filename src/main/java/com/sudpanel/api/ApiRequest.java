package com.sudpanel.api;

/**
 * 一条请求在「发送前组装」过程中的形态：地址、请求头、请求体。
 *
 * <p>组装是分段的 —— 先按作用域替换自定义变量，再算签名、补鉴权头 —— 每一段都产出同一个形状，
 * 所以共用一个类型。好处是「顺序」在代码里看得见：拿到的是哪一段的结果，就说明前面哪几段已经做过了，
 * 不会出现「签完名又去改变量」这种把签名内容和实际发送内容错开的写法。
 *
 * <p>之所以要一个自己的类型而不是继续用现成的三元组：替换与签名都是「改一处、也必须改对那一处」的操作，
 * 用散装参数传来传去时，很容易在某一处只传了两个、或者顺序传反 —— 而这类错误不会抛异常，
 * 只会让服务端回「认证失败」。有类型之后，调用点必须写全，编译器也能挡住顺序错。
 *
 * @param url     地址
 * @param headers 请求头（JSON 对象文本）
 * @param body    请求体
 */
public record ApiRequest(String url, String headers, String body) {
}
